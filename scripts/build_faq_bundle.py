"""Compile data/faq.json + data/course.json into widget/faq-bundle.js.

The widget loads it with a <script> tag (fetch() of local JSON is blocked on file://),
so the offline FAQ works with no network and no backend.

Usage: python scripts/build_faq_bundle.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    faq = json.loads((ROOT / "data" / "faq.json").read_text(encoding="utf-8"))
    course = json.loads((ROOT / "data" / "course.json").read_text(encoding="utf-8"))
    sections = {
        s["id"]: {
            "title_en": s["title_en"],
            "title_am": s.get("title_am") if s.get("verified_am") else None,
            "anchor": s["anchor"],
            "page_url": course["page_url"],
            "body_en": s["body_en"],
            "keywords_en": s.get("keywords_en", []),
            "keywords_am": s.get("keywords_am", []),
        }
        for s in course["sections"]
    }
    entries = [
        {k: f.get(k) for k in ("id", "section_id", "question_en", "question_am", "answer_en", "answer_am",
                                "keywords_en", "keywords_am", "action_id")}
        for f in faq
    ]
    bundle = {"version": 1, "course_id": course["course_id"], "entries": entries, "sections": sections}
    out = ROOT / "widget" / "faq-bundle.js"
    out.write_text("/* Generated by scripts/build_faq_bundle.py. Do not edit by hand. */\n"
                   "window.WWM_FAQ = " + json.dumps(bundle, ensure_ascii=False, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    print(f"Wrote {len(entries)} FAQ entries and {len(sections)} sections to {out}")


if __name__ == "__main__":
    main()
